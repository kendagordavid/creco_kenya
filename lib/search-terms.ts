/** Words that can distinguish a PBO question from everyday language. */
export function contentTerms(question: string): string[] {
  const raw = question.toLowerCase().match(/\w{3,}/g) ?? [];
  const seen = new Set<string>();
  const terms: string[] = [];
  for (const term of raw) {
    if (STOP_WORDS.has(term) || seen.has(term)) continue;
    seen.add(term);
    terms.push(term);
  }
  return terms;
}
